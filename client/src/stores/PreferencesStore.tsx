export type Locale = keyof typeof messages;
export type TranslationKey = keyof typeof messages.en;
export type Theme = 'light' | 'dark';

type PreferencesValue = {
  locale: Locale;
  theme: Theme;
  direction: 'ltr' | 'rtl';
  setLocale: (locale: Locale) => void;
  setTheme: (theme: Theme) => void;
  toggleTheme: () => void;
  t: (key: TranslationKey) => string;
};

const PreferencesContext = createContext<PreferencesValue | null>(null);

function readLocale(): Locale {
  return localStorage.getItem('memorybox-locale') === 'he' ? 'he' : 'en';
}

function readTheme(): Theme {
  return localStorage.getItem('memorybox-theme') === 'dark' ? 'dark' : 'light';
}

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(readLocale);
  const [theme, setTheme] = useState<Theme>(readTheme);
  const direction = locale === 'he' ? 'rtl' : 'ltr';
  const t = useCallback((key: TranslationKey) => messages[locale][key], [locale]);
  const toggleTheme = useCallback(() => setTheme((current) => current === 'light' ? 'dark' : 'light'), []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = direction;
    document.documentElement.dataset.theme = theme;
    const themeColor = document.querySelector<HTMLMetaElement>('meta[name="theme-color"]');
    if (themeColor) themeColor.content = theme === 'dark' ? '#14211c' : '#f6f8f5';
    localStorage.setItem('memorybox-locale', locale);
    localStorage.setItem('memorybox-theme', theme);
  }, [locale, theme, direction]);

  const value = useMemo<PreferencesValue>(() => ({
    locale,
    theme,
    direction,
    setLocale,
    setTheme,
    toggleTheme,
    t,
  }), [locale, theme, direction, toggleTheme, t]);

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  const value = useContext(PreferencesContext);
  if (!value) throw new Error('usePreferences must be used inside PreferencesProvider');
  return value;
}